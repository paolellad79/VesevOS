// Cerca la lingua del browser; se non c'e', italiano.
export function linguaIniziale() {
  let c = (navigator.language || 'it').slice(0, 2).toLowerCase();
  try { c = localStorage.getItem('vl') || c; } catch (e) { /* senza memoria del browser: lingua del browser */ }
  return TESTI[c] ? c : 'it';
}

export function t(chiave) {
  const d = TESTI[lingua] || TESTI.it;
  return d[chiave] !== undefined ? d[chiave] : (TESTI.it[chiave] !== undefined ? TESTI.it[chiave] : chiave);
}

export function tf(chiave, ...args) {
  return t(chiave).replace(/\{(\d+)\}/g, (m, i) => (args[+i] !== undefined ? String(args[+i]) : m));
}
